LIST=0
while [ $# -gt 0 ]; do
  case "$1" in
    --list)      LIST=1; shift ;;
    -h|--help)   usage; exit 0 ;;
    --)          shift; break ;;
    --*)         echo "unknown option: $1" >&2; usage; exit 2 ;;
    *)           break ;;
  esac
done
