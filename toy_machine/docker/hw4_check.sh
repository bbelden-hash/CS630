  got="$(printf '%s' "$raw" | normalize)"
  if [ "$got" = "$want" ]; then
    pass=$((pass + 1))
    printf 'PASS  %-12s %s\n' "$name" "$desc"
  else
    printf 'FAIL  %-12s %s\n' "$name" "$desc"
    printf '%s\n' "$want" | sed 's/^/         expected | /'
    printf '%s\n' "$got"  | sed 's/^/         yours    | /'
  fi
done <<< "$MANIFEST"

