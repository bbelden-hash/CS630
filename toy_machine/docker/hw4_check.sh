  [ -n "$name" ] || continue
  total=$((total + 1))
  printf '%s' "$ib64" | _b64d > "$tmp/case.asm"
  want="$(printf '%s' "$wb64" | _b64d | normalize)"
  raw="$(run_one "$@" "$tmp/case.asm" 2>"$tmp/stderr")"; status=$?
